import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { test } from "node:test";

const MIGRATIONS_DIR = join(process.cwd(), "supabase", "migrations");
const POLICY_MIGRATION = "20261020163108_enforce_explicit_public_grants.sql";
const RPC_MIGRATION = "20261020163339_restrict_workspace_color_rpc_execute.sql";
const POLICY_TIMESTAMP = 20261020163108;

function migrationTimestamp(name) {
  const match = /^(\d{14})_/.exec(name);
  return match ? Number(match[1]) : 0;
}

function hasPublicTableCreation(sql) {
  return /\bcreate\s+table(?:\s+if\s+not\s+exists)?\s+(?:public\.)?[a-z_][a-z0-9_]*/i.test(sql);
}

function auditPublicTableMigration(name, sql) {
  if (!hasPublicTableCreation(sql)) return [];

  const internalWithoutRls = /@m9r:internal-table-without-rls\b/i.test(sql);
  const issues = [];
  if (!internalWithoutRls && !/alter\s+table\s+(?:public\.)?[a-z_][a-z0-9_]*\s+enable\s+row\s+level\s+security/i.test(sql)) {
    issues.push(`${name}: every new public table must enable RLS or carry @m9r:internal-table-without-rls`);
  }
  if (!/\b(?:grant|revoke)\b/i.test(sql)) {
    issues.push(`${name}: every new public table must declare explicit grants or revokes`);
  }
  if (/(?:\bserial\b|generated\s+(?:always|by\s+default)\s+as\s+identity)/i.test(sql) && !/on\s+sequences/i.test(sql)) {
    issues.push(`${name}: sequence-backed tables must declare sequence grants or revokes`);
  }
  return issues;
}

test("the production grant guard is fail-closed and preserves the color-table contract", async () => {
  const sql = await readFile(join(MIGRATIONS_DIR, POLICY_MIGRATION), "utf8");
  assert.match(sql, /alter\s+default\s+privileges\s+for\s+role\s+postgres\s+in\s+schema\s+public/i);
  assert.match(sql, /revoke\s+all\s+on\s+tables\s+from\s+anon,\s*authenticated,\s*service_role/i);
  assert.match(sql, /revoke\s+all\s+on\s+functions\s+from\s+public,\s*anon,\s*authenticated,\s*service_role/i);
  assert.match(sql, /revoke\s+all\s+on\s+sequences\s+from\s+anon,\s*authenticated,\s*service_role/i);
  assert.match(sql, /revoke\s+all\s+on\s+table\s+public\.workspace_member_colors\s+from\s+public,\s*anon/i);
  assert.match(sql, /grant\s+select\s+on\s+table\s+public\.workspace_member_colors\s+to\s+authenticated/i);
  assert.match(sql, /grant\s+all\s+on\s+table\s+public\.workspace_member_colors\s+to\s+service_role/i);
});

test("the color allocation SECURITY DEFINER RPC is not callable by anon", async () => {
  const sql = await readFile(join(MIGRATIONS_DIR, RPC_MIGRATION), "utf8");
  assert.match(sql, /revoke\s+all\s+on\s+function\s+public\.allocate_workspace_member_color\(uuid,\s*uuid\)\s+from\s+public,\s*anon/i);
  assert.match(sql, /grant\s+execute\s+on\s+function\s+public\.allocate_workspace_member_color\(uuid,\s*uuid\)\s+to\s+authenticated,\s*service_role/i);
});

test("migrations added after the grant guard declare their public-table boundary", async () => {
  const names = (await readdir(MIGRATIONS_DIR)).filter((name) => name.endsWith(".sql"));
  const futureMigrations = names.filter((name) => migrationTimestamp(name) > POLICY_TIMESTAMP);
  const issues = [];
  for (const name of futureMigrations) {
    issues.push(...auditPublicTableMigration(name, await readFile(join(MIGRATIONS_DIR, name), "utf8")));
  }
  assert.deepEqual(issues, [], issues.join("\n"));
});

test("the migration audit rejects an unbounded public table", () => {
  const issues = auditPublicTableMigration(
    "20990101000000_bad.sql",
    "create table public.future_data (id uuid primary key);",
  );
  assert.deepEqual(issues, [
    "20990101000000_bad.sql: every new public table must enable RLS or carry @m9r:internal-table-without-rls",
    "20990101000000_bad.sql: every new public table must declare explicit grants or revokes",
  ]);
});

test("the migration audit accepts an explicitly bounded API table", () => {
  const issues = auditPublicTableMigration(
    "20990101000000_good.sql",
    `
      create table public.future_data (id bigint generated by default as identity primary key);
      alter table public.future_data enable row level security;
      grant select on public.future_data to authenticated;
      revoke all on sequences from anon, authenticated;
    `,
  );
  assert.deepEqual(issues, []);
});
